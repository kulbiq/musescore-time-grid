"""Renders the figure in the dialog's help: two bars spaced linearly by the extension, with a
picture aligned above them by the extension too, so the figure shows what the extension really does.

Writes equal_spacing/figure.png and equal_spacing/src/figure.js, which says where in the figure
the dialog draws its notes: the first note (From), the end of the time span (To), the beats between
them, the picture and the staff. Run after changing the spacing or the image alignment:
    python3 tools/make_figure.py
Needs MuseScore Studio (MSCORE, default /Applications/MuseScore 4.app) and the extension installed.
"""
import glob
import json
import math
import os
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
from add_image import main as add_image, png  # noqa: E402
from make_score import note  # noqa: E402

MSCORE = os.environ.get("MSCORE", "/Applications/MuseScore 4.app/Contents/MacOS/mscore")
LOGS = os.path.expanduser("~/Library/Application Support/MuseScore/MuseScore4/logs")
DPI = 200
BEATS = 8   # two bars of 4/4


def score(path):
    """Two bars of quarters, eighths and a half note on one staff, nothing else on the page."""
    bars = [
        [note("E", 5, 4, "quarter", 1), note("F", 5, 2, "eighth", 1), note("G", 5, 2, "eighth", 1),
         note("A", 5, 8, "half", 1)],
        [note(s, 5, 2, "eighth", 1) for s in "GFED"] + [note("C", 5, 4, "quarter", 1), note("E", 5, 4, "quarter", 1)],
    ]
    head = ("<attributes><divisions>4</divisions><key><fifths>0</fifths></key>"
            "<time><beats>4</beats><beat-type>4</beat-type></time>"
            "<clef><sign>G</sign><line>2</line></clef></attributes>")
    measures = "".join(f"<measure number='{i}'>{head if i == 1 else ''}{''.join(b)}</measure>"
                       for i, b in enumerate(bars, 1))
    with open(path, "w") as f:
        f.write("<?xml version='1.0' encoding='UTF-8'?><score-partwise version='4.0'><part-list>"
                "<score-part id='P1'><part-name print-object='no'></part-name></score-part></part-list>"
                f"<part id='P1'>{measures}</part></score-partwise>")


def wave(x, y, width, height):
    """A sound wave with a strike on every beat, so the strikes land on the notes."""
    beat = x * BEATS / width
    loud = math.exp(-(beat % 1) * 5) * 0.85 + 0.12
    texture = 0.8 + 0.2 * math.sin(x * 0.45)
    inside = abs(y - height / 2) <= loud * texture * height / 2 + 1
    return (70, 110, 190) if inside else (255, 255, 255)


def main():
    tmp = tempfile.mkdtemp()
    xml, plain, dropped, done = (os.path.join(tmp, n) for n in ("f.musicxml", "plain.mscz", "dropped.mscz", "done.mscz"))
    score(xml)
    subprocess.run([MSCORE, "-o", plain, xml], capture_output=True)
    add_image(plain, dropped, bars=(1,), data=png(800, 60, wave))
    job = os.path.join(tmp, "job.json")
    with open(job, "w") as f:
        json.dump([{"in": dropped, "out": done}], f)
    subprocess.run([MSCORE, "-j", job, "--extension", "musescore://extensions/equal_spacing?action=figure"],
                   capture_output=True)
    log = max(glob.glob(os.path.join(LOGS, "*")), key=os.path.getmtime)
    line = [ln for ln in open(log, encoding="utf-8") if "equal_spacing figure:" in ln][-1]
    g = json.loads(json.loads(line[line.index('"equal_spacing'):].strip()).split(": ", 1)[1])
    page = os.path.join(tmp, "page.png")
    subprocess.run([MSCORE, "-r", str(DPI), "-o", page, done], capture_output=True)
    page = sorted(glob.glob(os.path.join(tmp, "page*.png")))[0]

    px = g["mm"] / 25.4 * DPI   # pixels per spatium
    x0, x1 = g["left"] - 0.5, g["to"] + 1.5
    y0, y1 = g["pictureTop"] - 1.5, g["staffBottom"] + 4
    w, h = round((x1 - x0) * px), round((y1 - y0) * px)
    out = os.path.join(ROOT, "equal_spacing", "figure.png")
    subprocess.run(["sips", "-c", str(h), str(w), "--cropOffset", str(round(y0 * px)), str(round(x0 * px)),
                    page, "--out", out], check=True, capture_output=True)

    def fx(x):
        return round((x - x0) / (x1 - x0), 4)

    def fy(y):
        return round((y - y0) / (y1 - y0), 4)

    figure = {"width": w, "height": h, "from": fx(g["from"]), "to": fx(g["to"]), "beats": g["beats"],
              "pictureTop": fy(g["pictureTop"]), "pictureBottom": fy(g["pictureBottom"]),
              "staffTop": fy(g["staffTop"]), "staffBottom": fy(g["staffBottom"])}
    with open(os.path.join(ROOT, "equal_spacing", "src", "figure.js"), "w") as f:
        f.write("// Generated by tools/make_figure.py, do not edit: where figure.png shows what, as fractions\n"
                "// of its width and height, and its size in pixels.\n"
                f"var FIGURE = {json.dumps(figure)};\n")
    print(figure)


if __name__ == "__main__":
    main()
